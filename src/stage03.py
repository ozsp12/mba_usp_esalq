"""Stage 03 — K-means and thesis-style performance analysis.

The 2023 thesis documents six groups, per-feature averages, standard
deviations, dispersion (std/mean), z-score profiles and seven macro groups.
The original analysis notebook currently committed to GitHub is not valid
Jupyter JSON; the precise historical model configuration cannot be verified.
Therefore --scaler, --seed and --n-init are explicit and the clustering
outputs must not be represented as a byte-for-byte thesis replication.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA
from sklearn.preprocessing import MinMaxScaler, StandardScaler

from stage01 import CreatesDFDP

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "assets" / "tables_thesis"
FIGURES = ROOT / "assets" / "figures_thesis"


def save_plot(name: str) -> None:
    plt.tight_layout()
    plt.savefig(FIGURES / name, dpi=180, bbox_inches="tight")
    plt.close()


def run(dataset: Path = ROOT / "assets" / "dataset.csv",
        *, seed: int = 42, scaler: str = "standard", n_init: int = 10) -> None:
    for directory in (TABLES, FIGURES):
        if not directory.is_dir():
            raise FileNotFoundError(f"Provision the output directory first: {directory}")
    if dataset.suffix.lower() in (".xlsx", ".xls"):
        df = pd.read_excel(dataset, sheet_name=0, dtype={"id": str})
    else:
        df = pd.read_csv(dataset, dtype={"id": str})

    # The original 51-feature definitions and seven macro groupings come from
    # stage01; identifiers, state, generated labels and dummies are excluded.
    dictionary = CreatesDFDP(k=0.15).drop_duplicates(subset="Features")
    features = dictionary["Features"].tolist()
    feature_groups = dictionary.set_index("Features")["FeatureGrouping"]
    absent = [column for column in features if column not in df.columns]
    if absent:
        raise ValueError(f"Missing expected modeling columns: {absent}")
    x = df[features].apply(pd.to_numeric, errors="raise")
    if x.isna().any().any() or not np.isfinite(x.to_numpy()).all():
        raise ValueError("Missing/non-finite values in modeling features.")
    transforms = {"standard": StandardScaler, "minmax": MinMaxScaler}
    if scaler == "none":
        matrix = x.to_numpy()
    else:
        matrix = transforms[scaler]().fit_transform(x)

    model = KMeans(n_clusters=6, random_state=seed, n_init=n_init)
    labels = model.fit_predict(matrix)
    result = df.copy()
    result["Cluster"] = labels.astype(int) + 1
    result.to_csv(TABLES / "clustered_dataset.csv", index=False)

    sizes = result["Cluster"].value_counts().sort_index().rename_axis("Cluster")
    sizes.rename("Branches").to_csv(TABLES / "cluster_sizes.csv")
    means = result.groupby("Cluster")[features].mean().T
    stds = result.groupby("Cluster")[features].std().T
    dispersion = stds.div(means.where(means.ne(0))).replace([np.inf, -np.inf], np.nan)

    for name, table in (("cluster_means", means),
                        ("cluster_std", stds),
                        ("cluster_dispersion", dispersion)):
        output = table.copy()
        output.insert(0, "FeatureGrouping", feature_groups.reindex(output.index))
        output.to_csv(TABLES / f"{name}.csv", index_label="Features")

    # Within-feature normalization across the six cluster means. This is a
    # comparison profile, not a transformation of the original training data.
    row_std = means.std(axis=1, ddof=0).replace(0, np.nan)
    zscore = means.sub(means.mean(axis=1), axis=0).div(row_std, axis=0).fillna(0)
    zscore.insert(0, "FeatureGrouping", feature_groups.reindex(zscore.index))
    zscore.to_csv(TABLES / "cluster_zscores.csv", index_label="Features")

    group_means = (
        zscore.drop(columns="FeatureGrouping")
        .groupby(feature_groups.reindex(zscore.index), sort=True)
        .mean()
    )
    group_means.index.name = "FeatureGrouping"
    group_means.to_csv(TABLES / "macro_group_profiles.csv")
    macro_dispersion = dispersion.groupby(feature_groups.reindex(dispersion.index)).mean()
    macro_dispersion.index.name = "FeatureGrouping"
    macro_dispersion.to_csv(TABLES / "macro_group_dispersion.csv")

    # The group numbers generated by K-means have no intrinsic business order.
    # Compare them to historical/generated labels only as a contingency table.
    if "ClusterName" in df.columns:
        pd.crosstab(df["ClusterName"], result["Cluster"]).to_csv(
            TABLES / "cluster_contingency.csv"
        )
    if "Cluster" in df.columns:
        pd.crosstab(df["Cluster"], result["Cluster"]).to_csv(
            TABLES / "historical_cluster_crosswalk.csv"
        )

    pd.DataFrame([{
        "n_clusters": 6, "seed": seed, "n_init": n_init,
        "scaler": scaler, "inertia": model.inertia_,
        "n_branches": len(result), "n_features": len(features),
    }]).to_csv(TABLES / "model_parameters.csv", index=False)

    plt.figure(figsize=(7.5, 4.5))
    sns.barplot(x=sizes.index.astype(str), y=sizes.values)
    plt.xlabel("K-means cluster")
    plt.ylabel("Branches")
    plt.title("Number of branches by cluster")
    save_plot("cluster_sizes.png")

    for source, filename, title in (
        (dispersion, "dispersion.png", "Within-cluster dispersion (std / mean)"),
        (zscore.drop(columns="FeatureGrouping"), "zscore_profiles.png", "Cluster feature profiles — z-score"),
        (group_means, "macro_group_profiles.png", "Seven macro-groups — mean z-score"),
        (macro_dispersion, "macro_group_dispersion.png", "Mean dispersion per macro-group"),
    ):
        plt.figure(figsize=(11, max(5, min(14, 0.26 * len(source)))))
        sns.heatmap(source, cmap="coolwarm", center=0, annot=len(source) <= 8,
                    fmt=".2f", cbar=True)
        plt.tick_params(labelsize=7)
        plt.title(title)
        save_plot(filename)

    coordinates = PCA(n_components=2).fit_transform(matrix)
    plt.figure(figsize=(8, 6))
    sns.scatterplot(x=coordinates[:, 0], y=coordinates[:, 1],
                    hue=result["Cluster"].astype(str), s=15, alpha=0.55, linewidth=0)
    plt.title("K-means clusters — 2D PCA projection")
    plt.xlabel("PC1")
    plt.ylabel("PC2")
    save_plot("clusters_pca.png")
    print(f"stage03: {len(df)} branches, K=6; CSV tables -> {TABLES}; PNG figures -> {FIGURES}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "assets" / "dataset.csv")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--scaler", choices=("standard", "minmax", "none"), default="standard")
    parser.add_argument("--n-init", type=int, default=10)
    args = parser.parse_args()
    run(args.input, seed=args.seed, scaler=args.scaler, n_init=args.n_init)


if __name__ == "__main__":
    main()
